#!/usr/bin/env python3
"""Generates the 4+1 development view from the import statements of the code, so it always matches the code.
Run from the repository root:

    python scripts/generate-development-view.py

Writes docs/c4/7-development-view.mmd (the package groups and how they depend on each other) and
docs/c4/7-development-view.md (every package and the packages it imports), and copies that table into
docs/c4-model.md between its development-view markers. Fails if two packages import each other (a cycle) or a
package imports one of a higher layer (GROUPS lists the layers top to bottom). Every package may use "common";
those dependencies are left out. CI runs it and fails if the committed files differ from what it generates.
"""
import collections
import os
import re

BASE = 'src/main/java/pt/isep/sidis/flightops'
DESCRIPTION = {
    'api': 'REST controllers', 'api.dto': 'request / response objects', 'security': 'sign-in, users',
    'services': 'business logic', 'bootstrap': 'sample data',
    'cluster': 'instances, owner of each aircraft', 'peers': 'calls to the other instances',
    'replication': 'outbox, copies, catch-up', 'resilience': 'retry, circuit breaker, health',
    'monitoring': 'monitoring API, dashboard', 'repositories': 'Spring Data JPA', 'domain': 'entities',
    'clients': 'calls to the other services', 'stub': 'built-in data (test mode)',
    'common': 'crypto, exceptions, HTTP client, JWT, metrics, tracing',
}
GROUPS = [   # layers, top to bottom: a package only uses packages of its own layer or of layers below
    ('Entry points', ['api', 'monitoring', 'security', 'bootstrap']),
    ('Application', ['services']),
    ('Distribution', ['replication', 'peers', 'cluster']),
    ('Integration', ['clients', 'stub', 'resilience']),
    ('Data', ['repositories', 'api.dto', 'domain']),
    ('Shared', ['common']),
]


def node(package):
    return 'common' if package.startswith('common') else package


def scan():
    deps = collections.defaultdict(set)
    classes = collections.Counter()
    for root, _, files in os.walk(BASE):
        package = os.path.relpath(root, BASE).replace(os.sep, '.')
        if package == '.':
            continue
        for name in files:
            if not name.endswith('.java'):
                continue
            classes[node(package)] += 1
            source = open(os.path.join(root, name), encoding='utf-8').read()
            for imported in re.findall(r'^import pt\.isep\.sidis\.flightops\.([a-z.]+)\.[A-Z]', source, re.M):
                a, b = node(package), node(imported)
                if a != b and b != 'common':
                    deps[a].add(b)
    return deps, classes


def main():
    deps, classes = scan()
    group_of = {m: title for title, members in GROUPS for m in members}
    unknown = set(classes) - set(group_of)
    if unknown:
        raise SystemExit(f'packages missing from GROUPS: {sorted(unknown)}')
    cycles = sorted({tuple(sorted((a, b))) for a in deps for b in deps[a] if a in deps.get(b, set())})

    order = {title: i for i, (title, _) in enumerate(GROUPS)}
    upward = sorted(f'{a} -> {b}' for a in deps for b in deps[a] if order[group_of[b]] < order[group_of[a]])

    # group level: how many package dependencies go from one group to another
    between = collections.Counter()
    for a in deps:
        for b in deps[a]:
            if group_of[a] != group_of[b]:
                between[(group_of[a], group_of[b])] += 1

    gid = {title: f'G{i}' for i, (title, _) in enumerate(GROUPS)}
    with open('docs/c4/7-development-view.mmd', 'w', encoding='utf-8', newline='\n') as out:
        w = lambda line: out.write(line + '\n')
        w('---\nconfig:\n  fontFamily: arial\n---')
        w('%% Development view (4+1): package groups of pt.isep.sidis.flightops and how they depend on each other.')
        w('%% Generated by scripts/generate-development-view.py from the import statements - do not edit by hand.')
        w('flowchart TB')
        for title, members in GROUPS:
            lines = '<br/>'.join(f'{m} ({classes[m]})' for m in members)
            w(f'    {gid[title]}["<b>{title}</b><br/><br/>{lines}"]')
        for (a, b), n in sorted(between.items()):
            w(f'    {gid[a]} -->|"{n}"| {gid[b]}')
        w('    classDef group fill:#ffffff,stroke:#5d82a8,color:#000000')
        w('    class ' + ','.join(gid.values()) + ' group')

    with open('docs/c4/7-development-view.md', 'w', encoding='utf-8', newline='\n') as out:
        w = lambda line: out.write(line + '\n')
        w('<!-- Generated by scripts/generate-development-view.py from the import statements - do not edit by hand. -->')
        w('| Group | Package | Classes | Purpose | Imports (besides `common`) |')
        w('|---|---|---|---|---|')
        for title, members in GROUPS:
            for m in members:
                imports = ', '.join(f'`{d}`' for d in sorted(deps.get(m, ()))) or '-'
                w(f'| {title} | `{m}` | {classes[m]} | {DESCRIPTION[m]} | {imports} |')
        w('')
        if cycles:
            w('Packages that import each other (cycles): ' + ', '.join(f'`{a}` ↔ `{b}`' for a, b in cycles) + '.')
        else:
            w('No package cycles: no two packages import each other.')

    # the same table inside docs/c4-model.md, between its markers
    doc = 'docs/c4-model.md'
    table = open('docs/c4/7-development-view.md', encoding='utf-8').read().split('\n', 1)[1].rstrip()
    text = open(doc, encoding='utf-8').read()
    begin, end = '<!-- development-view:start -->', '<!-- development-view:end -->'
    if begin in text and end in text:
        text = text[:text.index(begin) + len(begin)] + '\n' + table + '\n' + text[text.index(end):]
        open(doc, 'w', encoding='utf-8', newline='\n').write(text)

    print(f'{len(classes)} packages, {sum(len(v) for v in deps.values())} dependencies, {len(cycles)} cycle(s), '
          f'{len(upward)} upward')
    if cycles or upward:
        raise SystemExit('package cycles or upward dependencies: ' + ', '.join(upward + [f'{a} <-> {b}' for a, b in cycles]))


if __name__ == '__main__':
    main()
